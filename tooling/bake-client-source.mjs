#!/usr/bin/env node
/**
 * Bakes an Uplink's `ClientSource` and `ExpectedClientHash` into generated C#,
 * so the running mod can tell the app where its client bundle lives and what it
 * should hash to.
 *
 * ## Why the mod has to say it, rather than the app knowing
 *
 * The app must not carry a list of Uplink ids: an Uplink this repo has never
 * heard of has to work identically to one it ships. So the app learns an
 * Uplink's client URL from the roster the mod publishes, and
 * `UplinkManifest.ClientSource` is the field it comes from.
 *
 * Every link in that chain already existed and nothing populated the field:
 * `ChannelEngine.BuildSystemUplinksPayload` emits `clientSource` onto
 * `system.uplinks`, `@ksp-gonogo/sitrep-sdk` types it, and the app's loader
 * consumes it (`descriptorFromClientSource`, `loadThirdParty`). This is the
 * missing two fields.
 *
 * ## Url and DevPath are different KINDS of value, which is why only one is declared
 *
 * `Url` is the distributable: where the release bundle will live for anyone who
 * installs this Uplink. It belongs in `uplink.json` next to the Uplink, is the
 * same for every user, and ships inside the released DLL.
 *
 * `DevPath` is the author's own machine: a dev server on localhost or a LAN
 * address, meaningful to one person for one afternoon. The loader PREFERS it
 * when present (`resolveClientBundleUrl`), which is exactly right for a dev loop
 * and exactly wrong to ship. So it is never declared in `uplink.json` and comes
 * only from `--dev-path` or `GONOGO_UPLINK_DEV_PATH` at build time, and a build
 * that was given one says so loudly, because a released DLL pointing at somebody's
 * laptop is a silent way to ship a broken Uplink.
 *
 * ## The hash closes a three-way check that has been running two-way
 *
 * The loader compares three independent witnesses of the client bundle: the
 * registry index's hash, the bytes it actually fetched, and `expectedClientHash`
 * from the mod. The third has been null everywhere, because
 * `mod/scripts/bake-client-hash.mjs` exists, is unit-tested, is documented to
 * authors, and nothing has ever invoked it, so every `ExpectedClientHash.g.cs`
 * reads `""`. The check degrades to two-way and says nothing about it.
 *
 * It is baked here because this is the only point where both halves exist: the
 * bundle has been built and hashed, and the DLL has not been compiled yet. That
 * ordering is the whole reason a release is two passes.
 *
 * Usage:
 *   bake-client-source.mjs <uplink-dir-name> [--dev-path <url>] [--hash <sha256-...>]
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const args = process.argv.slice(2);
const name = args[0];
const flag = (which) =>
  args.includes(which) ? args[args.indexOf(which) + 1] : undefined;
const devPath = flag("--dev-path") ?? process.env.GONOGO_UPLINK_DEV_PATH ?? "";
const hash = flag("--hash") ?? "";

if (!name) {
  console.error(
    "usage: bake-client-source.mjs <uplink-dir-name> [--dev-path <url>] [--hash <sha256-...>]",
  );
  process.exit(2);
}

const uplinkDir = join(ROOT, "uplinks", name);
const declared = JSON.parse(
  readFileSync(join(uplinkDir, "uplink.json"), "utf8"),
);

/**
 * An Uplink with no client half has nothing to point at, and says so rather than
 * baking an empty URL: `ClientSource` must be null for a mod-only Uplink, and an
 * empty string is not null.
 */
if (!declared.client?.url) {
  console.log(
    `${declared.id}: no client.url in uplink.json, so ClientSource stays null (mod-only Uplink)`,
  );
  process.exit(0);
}

if (hash && !/^sha256-[0-9a-f]{64}$/.test(hash)) {
  console.error(
    `✖ ${declared.id}: --hash "${hash}" is not a sha256-<64 hex> digest. A malformed hash bakes a\n` +
      "  value the loader can never match, which fails as tampering rather than as a bad build.",
  );
  process.exit(1);
}

const namespace = declared.csharpNamespace;
if (!namespace) {
  console.error(
    `✖ ${declared.id}: uplink.json declares no "csharpNamespace", so this cannot know where to\n` +
      "  emit. It is read rather than derived from the id, because the two do not match in general.",
  );
  process.exit(1);
}

const cs = (literal) => JSON.stringify(String(literal));

/*
 * Provenance, from the same uplink.json. It reaches the consent dialog, which is
 * the one place it matters: an operator is being asked to execute a bundle
 * fetched from a URL they did not choose, so it should say who wrote it. Until
 * the mod emitted these the dialog said `by unknown` for every Uplink.
 */
writeFileSync(
  join(uplinkDir, "mod", "Provenance.g.cs"),
  `// <auto-generated> Written by tooling/bake-client-source.mjs. DO NOT EDIT.
namespace ${namespace}
{
    internal static class Provenance
    {
        public const string Name = ${cs(declared.name ?? "")};
        public const string Author = ${cs(declared.author ?? "")};
        public const string Repo = ${cs(declared.repo ?? "")};
    }
}
`,
);

writeFileSync(
  join(uplinkDir, "mod", "ClientSource.g.cs"),
  `// <auto-generated> Written by tooling/bake-client-source.mjs. DO NOT EDIT.
//
// Url comes from uplink.json and ships. DevPath comes from the build that
// produced this file and must not: the loader PREFERS DevPath when it is
// non-empty, so a released DLL carrying one sends every user to a machine that
// is not theirs.
namespace ${namespace}
{
    internal static class ClientSource
    {
        public const string Url = ${cs(declared.client.url)};
        public const string DevPath = ${cs(devPath)};
    }
}
`,
);

writeFileSync(
  join(uplinkDir, "mod", "ExpectedClientHash.g.cs"),
  `// <auto-generated> Written by tooling/bake-client-source.mjs. DO NOT EDIT.
//
// The sha256 of the client bundle this DLL was built alongside. Empty when the
// bundle has not been hashed yet, which leaves Manifest.ExpectedClientHash null
// and the loader's three-way check running two-way, recorded as pending rather
// than passed.
namespace ${namespace}
{
    internal static class ExpectedClientHash
    {
        public const string Value = ${cs(hash)};
    }
}
`,
);

console.log(`${declared.id}: baked ClientSource + ExpectedClientHash`);
console.log(`  Url      ${declared.client.url}`);
console.log(`  by       ${declared.author ?? "(nobody declared)"}`);
if (devPath) {
  console.log(`  DevPath  ${devPath}`);
  console.log(
    "  ⚠ DEV BUILD. The loader prefers DevPath over Url, so this DLL sends every client to that\n" +
      "    address. Rebuild without --dev-path before releasing.",
  );
} else {
  console.log("  DevPath  (none, release shape)");
}
console.log(
  hash
    ? `  Hash     ${hash}, so the loader's third witness is live`
    : "  Hash     (none) so the loader's three-way check runs two-way and records the mod arm pending",
);
