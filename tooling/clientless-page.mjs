/**
 * The generated README of an Uplink that has no client.
 *
 * `uplink-tools docs` writes an Uplink's page from what its client registers, so
 * it has nothing to read for an Uplink that is only a plugin. That page is
 * written here instead, from the one file such an Uplink has, `uplink.json`:
 * its name, its `description`, the mod it pairs with and the folder it installs
 * into. The sections and their wording are the ones `uplink-tools docs` writes
 * for the others, minus what only a client has (widgets, topics, commands).
 */

const GONOGO_URL = "https://ksp-gonogo.github.io/";

/** First line of a README this module wrote, and what tells it from a typed one. */
export const CLIENTLESS_BANNER = "<!-- Generated by `tooling/uplink-docs.mjs`.";

/** The releases page filtered to one Uplink's tags, or the plain releases page off GitHub. */
function releasesUrl(repo, id) {
  if (!repo) return undefined;
  const base = repo.replace(/\/+$/, "").replace(/\.git$/, "");
  try {
    if (new URL(base).hostname !== "github.com") return `${base}/releases`;
  } catch {
    return undefined;
  }
  return `${base}/releases?q=${encodeURIComponent(`${id}-v`)}`;
}

/** What an Uplink's `uplink.json` is missing for its page, as a list of reasons. */
export function clientlessDeclarationFaults(declared) {
  const faults = [];
  for (const key of ["id", "name", "gamedata"]) {
    if (typeof declared[key] !== "string" || declared[key].trim() === "") {
      faults.push(`uplink.json declares no \`${key}\``);
    }
  }
  if (typeof declared.description !== "string" || declared.description.trim() === "") {
    faults.push(
      "uplink.json declares no `description`, and the page opens with it: add one or two sentences saying what the Uplink does",
    );
  }
  return faults;
}

/** The README of a client-less Uplink, from its parsed `uplink.json`. */
export function buildClientlessReadme(declared) {
  const faults = clientlessDeclarationFaults(declared);
  if (faults.length > 0) throw new Error(faults.join("\n"));

  const label = `${declared.name} Uplink`;
  const mod = declared.mod;
  const releases = releasesUrl(declared.repo, declared.id);
  const details = [
    ["Uplink id", `\`${declared.id}\``],
    ["Wraps", mod?.tier ? `${mod.name ?? ""} (${mod.tier})`.trim() : undefined],
  ].filter(([, value]) => value !== undefined && value !== "");

  const out = [
    `${CLIENTLESS_BANNER} Do not edit this file: it is written`,
    "     from the Uplink's uplink.json. -->",
    "",
    `# ${declared.name}`,
    "",
    declared.description.replace(/\s+/g, " ").trim(),
    "",
    `An Uplink for [Gonogo](${GONOGO_URL}), the mission-control dashboard for Kerbal Space Program that runs in a web browser on any screen.`,
    "",
    ...(mod?.name
      ? [`Built against ${mod.name}${mod.builtAgainst ? ` ${mod.builtAgainst}` : ""}.`, ""]
      : []),
    "## Install",
    "",
    `Install the ${label} with CKAN: search for \`${declared.gamedata}\`, tick it and apply. CKAN also installs Gonogo itself${mod?.name ? ` and ${mod.name}` : ""}.`,
    "",
    `Without CKAN, download \`${declared.gamedata}.zip\` from the releases page, unpack it into your Kerbal Space Program folder so that it lands in \`GameData/${declared.gamedata}\`, and install Gonogo the same way.`,
    "",
    ...(releases ? [`Releases: ${releases}`, ""] : []),
    "## For developers",
    "",
    "<details>",
    "<summary>Uplink details</summary>",
    "",
    "| | |",
    "| --- | --- |",
    ...details.map(([name, value]) => `| ${name} | ${value} |`),
    "",
    "</details>",
    "",
  ];
  return out.join("\n");
}
