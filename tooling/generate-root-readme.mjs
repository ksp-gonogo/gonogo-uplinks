#!/usr/bin/env node
/**
 * Regenerates the root README's Uplink table from what is actually on disk.
 *
 * A monorepo needs a front door, and a flat single-Uplink repo does not: that is
 * why the template is flat and this exists only here. An Uplink's own README stays
 * where it is and stays the real one; this links to them so a stranger landing on
 * the repo root is not looking at nine directories and guessing.
 *
 * Generated rather than hand-maintained, for the reason every list in this project
 * is: a hand-kept table has no gate on its own completeness, so it silently stops
 * describing the repo the first time somebody adds an Uplink and forgets. The
 * matrix is discovered, and so is this, from the same `uplink.json` files.
 *
 * Usage:
 *   generate-root-readme.mjs           rewrite the table
 *   generate-root-readme.mjs --check   fail if it is out of date, for CI
 */

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const README = join(ROOT, "README.md");
const START = "<!-- uplinks:start -->";
const END = "<!-- uplinks:end -->";

const check = process.argv.includes("--check");

const legs = JSON.parse(
  execFileSync("node", [join(ROOT, "scripts/uplink-matrix.mjs")], {
    encoding: "utf8",
  }),
);

const rows = legs.map((leg) => {
  const declared = JSON.parse(
    readFileSync(join(ROOT, "uplinks", leg.name, "uplink.json"), "utf8"),
  );
  // Link the Uplink's OWN README when it has one, the directory otherwise, so a
  // row never points at a page that does not exist.
  const readme = join(ROOT, "uplinks", leg.name, "client", "README.md");
  const href = existsSync(readme)
    ? `uplinks/${leg.name}/client/README.md`
    : `uplinks/${leg.name}/`;
  const wraps = declared.mod
    ? `${declared.mod.name} ${declared.mod.builtAgainst} (${declared.mod.tier})`
    : "nothing, self-contained";
  return `| [${declared.name}](${href}) | \`${declared.id}\` | ${wraps} | ${declared.author} |`;
});

const table = [
  "",
  "| Uplink | id | wraps | author |",
  "|---|---|---|---|",
  ...rows,
  "",
  `_${rows.length} Uplink(s), generated by \`tooling/generate-root-readme.mjs\` from each \`uplink.json\`._`,
  "",
].join("\n");

const current = readFileSync(README, "utf8");
if (!current.includes(START) || !current.includes(END)) {
  console.error(
    `✖ README.md has no ${START} / ${END} markers, so there is nowhere to write the table and this\n` +
      "  would silently do nothing. Add them where the table belongs.",
  );
  process.exit(1);
}

const next =
  current.slice(0, current.indexOf(START) + START.length) +
  table +
  current.slice(current.indexOf(END));

if (check) {
  if (next !== current) {
    console.error(
      "✖ the root README's Uplink table is out of date. Run:\n" +
        "    node tooling/generate-root-readme.mjs\n" +
        "  An Uplink was added, renamed, or changed what it wraps, and the front door still\n" +
        "  describes the repo as it was.",
    );
    process.exit(1);
  }
  console.log(`root README table is current (${rows.length} Uplink(s)).`);
  process.exit(0);
}

writeFileSync(README, next);
console.log(`root README table regenerated (${rows.length} Uplink(s)).`);
